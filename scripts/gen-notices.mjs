// Usage: npm run notices
// Writes THIRD_PARTY_NOTICES.md: every Rust crate linked into the Windows exe and every npm
// package bundled into the window, with its license and license text. The About screen shows
// this file, and it ships in the release. Uses only cargo and Node, nothing to install.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const run = (cmd, args) =>
  execFileSync(cmd, args, { cwd: root, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });

/** @type {Array<{ ecosystem: string, name: string, version: string, license: string, url: string, texts: string[] }>} */
const packages = [];

/** Text of the license files found in a package folder. */
function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => /^(licen[sc]e|copying|notice|unlicense)/i.test(f))
    .map((f) => readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim())
    .filter(Boolean);
}

// Rust: the crates that end up in the Windows build (no dev or build-only crates).
const wanted = new Set(
  run('cargo', [
    'tree',
    '-e',
    'normal',
    '--prefix',
    'none',
    '--target',
    'x86_64-pc-windows-msvc',
    '-p',
    'jj-pdf-studio'
  ])
    .split('\n')
    .map((l) => /^(\S+) v(\S+)/.exec(l))
    .filter(Boolean)
    .map((m) => `${m[1]} ${m[2]}`)
);
const metadata = JSON.parse(
  run('cargo', [
    'metadata',
    '--format-version',
    '1',
    '--locked',
    '--filter-platform',
    'x86_64-pc-windows-msvc'
  ])
);
for (const p of metadata.packages) {
  if (!wanted.has(`${p.name} ${p.version}`) || p.source === null) continue; // skip our own crates
  packages.push({
    ecosystem: 'Rust',
    name: p.name,
    version: p.version,
    license: p.license ?? 'see repository',
    url: p.repository ?? p.homepage ?? `https://crates.io/crates/${p.name}`,
    texts: licenseTexts(dirname(p.manifest_path))
  });
}

// npm: what ends up in the bundle is the runtime dependencies plus Svelte's runtime.
const pkgDir = (name, from) => {
  for (let dir = from; ; dir = dirname(dir)) {
    const candidate = join(dir, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return candidate;
    if (dir === dirname(dir)) return null;
  }
};
const own = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const seen = new Set();
const visit = (name, from) => {
  const dir = pkgDir(name, from);
  if (!dir || seen.has(dir)) return;
  seen.add(dir);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  packages.push({
    ecosystem: 'npm',
    name: pkg.name,
    version: pkg.version,
    license: typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'see package'),
    url: (repo ?? pkg.homepage ?? `https://www.npmjs.com/package/${pkg.name}`)
      .replace(/^git\+/, '')
      .replace(/\.git$/, ''),
    texts: licenseTexts(dir)
  });
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir);
};
for (const dep of [...Object.keys(own.dependencies), 'svelte']) visit(dep, root);

packages.sort((a, b) => a.ecosystem.localeCompare(b.ecosystem) || a.name.localeCompare(b.name));

// License texts are shared by many packages; print each distinct text once.
const texts = new Map(); // hash -> { text, users: string[] }
for (const p of packages) {
  for (const text of p.texts) {
    const hash = createHash('sha256').update(text).digest('hex');
    const entry = texts.get(hash) ?? { text, users: [] };
    entry.users.push(`${p.name} ${p.version}`);
    texts.set(hash, entry);
  }
}

let out = `# Third-party notices

JJ PDF Studio is licensed under the Apache License 2.0 (see \`LICENSE\`). It includes the open
source software listed below, each under its own license. This file is generated by
\`npm run notices\`; do not edit it by hand.

The Inter font is bundled under the SIL Open Font License 1.1.

## Packages (${packages.length})

| Package | Version | License | Source |
| --- | --- | --- | --- |
`;
for (const p of packages) {
  out += `| ${p.name} (${p.ecosystem}) | ${p.version} | ${p.license.replace(/\|/g, '/')} | ${p.url} |\n`;
}
out += `\n## License texts\n`;
let n = 0;
for (const { text, users } of texts.values()) {
  n++;
  out += `\n### ${n}. Used by: ${users.join(', ')}\n\n\`\`\`text\n${text}\n\`\`\`\n`;
}
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), out);
console.log(
  `Wrote THIRD_PARTY_NOTICES.md: ${packages.length} packages, ${texts.size} license texts.`
);
